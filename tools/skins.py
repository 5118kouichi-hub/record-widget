def rrect(x, y, w, h, r):
    return (f"M{x + r},{y}h{w - 2 * r}a{r},{r} 0,0 1,{r},{r}v{h - 2 * r}a{r},{r} 0,0 1,-{r},{r}"
            f"h-{w - 2 * r}a{r},{r} 0,0 1,-{r},-{r}v-{h - 2 * r}a{r},{r} 0,0 1,{r},-{r}z")


def circle(cx, cy, r):
    return f"M{cx - r:.1f},{cy:.1f}a{r:.1f},{r:.1f} 0,1 0,{2 * r:.1f} 0a{r:.1f},{r:.1f} 0,1 0,{-2 * r:.1f} 0z"


def path(d, color=None, stroke=None, width=None, grad=None):
    attrs = f'android:pathData="{d}"'
    if color:
        attrs += f' android:fillColor="{color}"'
    if stroke:
        attrs += f' android:strokeColor="{stroke}" android:strokeWidth="{width}"'
    if grad:
        return f"""    <path {attrs}>
        <aapt:attr name="android:fillColor">
            {grad}
        </aapt:attr>
    </path>
"""
    return f"    <path {attrs} />\n"


def lin(x1, y1, x2, y2, *stops):
    items = "".join(f'<item android:offset="{o}" android:color="{c}" />' for o, c in stops)
    return (f'<gradient android:type="linear" android:startX="{x1}" android:startY="{y1}" '
            f'android:endX="{x2}" android:endY="{y2}">{items}</gradient>')


def rad(cx, cy, r, *stops):
    items = "".join(f'<item android:offset="{o}" android:color="{c}" />' for o, c in stops)
    return (f'<gradient android:type="radial" android:centerX="{cx}" android:centerY="{cy}" '
            f'android:gradientRadius="{r}">{items}</gradient>')


def jacket_shadow():
    x, y, s = JACKET
    return path(rrect(x + 2, y + 3, s, s, 2), "#33000000")


def platter(rim, mat, ring_extra=""):
    out = path(circle(CX, CY, R + 4), rim)
    out += ring_extra
    out += path(circle(CX, CY, R), grad=rad(CX, CY - 20, R * 1.3, (0, mat[0]), (1, mat[1])))
    return out


def spindle_shadow():
    return path(circle(CX + 1.5, CY + 2, R - 2), "#22000000")


