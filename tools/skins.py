def arm_anim(skin, kind):
    """Realistic arm: lowers onto the record after the platter starts, then rides the
    slightly warped record (tiny wobble); lifts and swings back when stopped."""
    if kind == "in":
        base, anims = f"tonearm_{skin}_up", f"""
                <objectAnimator android:propertyName="rotation" android:valueType="floatType"
                    android:valueFrom="0" android:valueTo="{DOWN_DEG}" android:startOffset="250"
                    android:duration="1100" android:interpolator="@android:interpolator/accelerate_decelerate" />
                <objectAnimator android:propertyName="rotation" android:valueType="floatType"
                    android:valueFrom="{DOWN_DEG}" android:valueTo="{DOWN_DEG + 0.6}" android:duration="900"
                    android:repeatCount="infinite" android:repeatMode="reverse"
                    android:interpolator="@android:interpolator/accelerate_decelerate" />"""
    else:
        base, anims = f"tonearm_{skin}_down", f"""
                <objectAnimator android:propertyName="rotation" android:valueType="floatType"
                    android:valueFrom="{DOWN_DEG}" android:valueTo="0"
                    android:duration="900" android:interpolator="@android:interpolator/accelerate_decelerate" />
                <objectAnimator android:propertyName="rotation" android:valueType="floatType"
                    android:valueFrom="0" android:valueTo="0" android:duration="3600000"
                    android:repeatCount="infinite" />"""
    targets = "".join(f"""
    <target android:name="{name}">
        <aapt:attr name="android:animation">
            <set android:ordering="sequentially">{anims}
            </set>
        </aapt:attr>
    </target>""" for name in ("arm", "shadow"))
    return f"""<?xml version="1.0" encoding="utf-8"?>
<!-- GENERATED by tools/gen_widget_res.py (tools/skins.py): tonearm {kind} ({skin}) -->
<animated-vector xmlns:android="http://schemas.android.com/apk/res/android"
    xmlns:aapt="http://schemas.android.com/aapt"
    android:drawable="@drawable/{base}">{targets}
</animated-vector>
"""
