#!/usr/bin/env python3
"""Generates the widget's record drawables and layouts (run from the repo root).

The record turns with an indeterminate ProgressBar whose drawable is an AnimatedVectorDrawable:
the launcher runs it, so the app never redraws frames. RemoteViews cannot change a
ProgressBar's drawable, so there is one spin-up and one spin-down bar per start angle
(every 30 degrees), plus a still record per angle for the paused state.

  spin-up   : accelerate 0 -> 200 deg/s over 1.2 s (turns 120 deg), then 33 1/3 rpm forever
  spin-down : decelerate 200 -> 0 deg/s over 1.5 s (turns 150 deg), then holds still
Both phase lengths are multiples of 30 deg, so every phase starts and ends on the grid.
"""
