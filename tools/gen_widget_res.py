# ---- retro portable player (home-screen widget), seen from the front and above --------
# Body in a 300x170 viewport: the cream top (foreshortened) and the red front of the case.
BODY_W, BODY_H = 300, 170
DECK_BOTTOM = 118        # top face ends here; then the deck edge and the red front
FRONT_TOP = 124
DISC_BOX = 200           # record box (100x100 disc viewport), viewport units
DISC_LEFT, DISC_TOP = 106, 0  # keeps the tonearm pivot inside the case
DISC_CX = DISC_LEFT + 0.44 * DISC_BOX
DISC_CY = DISC_TOP + (CY + TILT_SHIFT) / 100 * DISC_BOX
DISC_RX = 0.42 * DISC_BOX
DISC_RY = DISC_RX * TILT


def ellipse(cx, cy, rx, ry):
    return f"M{cx - rx:.1f},{cy:.1f}a{rx:.1f},{ry:.1f} 0,1 0,{2 * rx:.1f} 0a{rx:.1f},{ry:.1f} 0,1 0,{-2 * rx:.1f} 0z"


def knob(cx, cy, pointer_deg):
    import math
    rx, ry, hgt = 10, 6, 4
    a = math.radians(pointer_deg)
    px, py = cx + math.sin(a) * rx * 0.7, cy - hgt - math.cos(a) * ry * 0.7
    return f"""    <path android:fillColor="#59000000" android:pathData="{ellipse(cx + 2, cy + 2, rx + 1, ry + 1)}" />
    <path android:fillColor="#FF151515" android:pathData="M{cx - rx},{cy - hgt}v{hgt}a{rx},{ry} 0,0 0,{2 * rx},0v{-hgt}z" />
    <path android:fillColor="#FF151515" android:pathData="{ellipse(cx, cy, rx, ry)}" />
    <path android:fillColor="#FF3C3C3C" android:pathData="{ellipse(cx, cy - hgt, rx, ry)}" />
    <path android:strokeColor="#FFE0E0E0" android:strokeWidth="1.4" android:strokeLineCap="round"
        android:pathData="M{cx},{cy - hgt}L{px:.1f},{py:.1f}" />"""


