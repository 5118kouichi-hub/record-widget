#!/usr/bin/env python3
"""Generates the widget's record drawables and layouts (run from the repo root).

The record turns with an indeterminate ProgressBar whose drawable is an AnimatedVectorDrawable:
the launcher runs it, so the app never redraws frames. RemoteViews cannot change a
ProgressBar's drawable, so there is one spin-up and one spin-down bar per start angle
(every 30 degrees), plus a still record per angle for the paused state.

  spin-up   : accelerate 0 -> 200 deg/s over 1.2 s (turns 120 deg), then 33 1/3 rpm forever
  spin-down : decelerate 200 -> 0 deg/s over 1.5 s (turns 150 deg), then holds still
Both phase lengths are multiples of 30 deg, so every phase starts and ends on the grid.
"""
import os

RES = "app/src/main/res"
STEP = 30
ANGLES = list(range(0, 360, STEP))
UP_MS, UP_DEG = 1200, 120      # 2*120/1.2 = 200 deg/s at the end (accelerate_quad)
DOWN_MS, DOWN_DEG = 1500, 150  # 2*150/1.5 = 200 deg/s at the start (decelerate_quad)
TURN_MS = 1800                 # 360 deg / 1.8 s = 200 deg/s = 33 1/3 rpm
CX, CY = 44, 56                # disc center in the shared 100x100 viewport

DISC_PATHS = """
        <!-- vinyl -->
        <path android:fillColor="#FF111111"
            android:pathData="M2,56a42,42 0,1 0,84 0a42,42 0,1 0,-84 0z" />
        <!-- grooves -->
        <path android:strokeColor="#FF2C2C2C" android:strokeWidth="0.6"
            android:pathData="M6,56a38,38 0,1 0,76 0a38,38 0,1 0,-76 0z" />
        <path android:strokeColor="#FF2C2C2C" android:strokeWidth="0.6"
            android:pathData="M12,56a32,32 0,1 0,64 0a32,32 0,1 0,-64 0z" />
        <path android:strokeColor="#FF2C2C2C" android:strokeWidth="0.6"
            android:pathData="M18,56a26,26 0,1 0,52 0a26,26 0,1 0,-52 0z" />
        <path android:strokeColor="#FF2C2C2C" android:strokeWidth="0.6"
            android:pathData="M24,56a20,20 0,1 0,40 0a20,20 0,1 0,-40 0z" />
        <!-- uneven groove shine: turns with the record so the spin is visible -->
        <path android:strokeColor="#33FFFFFF" android:strokeWidth="0.8" android:strokeLineCap="round"
            android:pathData="M15,46a30,30 0,0 1,10 -14" />
        <path android:strokeColor="#26FFFFFF" android:strokeWidth="0.8" android:strokeLineCap="round"
            android:pathData="M73,66a30,30 0,0 1,-10 14" />
        <!-- center label -->
        <path android:fillColor="#FFE64A19"
            android:pathData="M30,56a14,14 0,1 0,28 0a14,14 0,1 0,-28 0z" />
        <path android:strokeColor="#FFFFAB91" android:strokeWidth="0.6"
            android:pathData="M34,56a10,10 0,1 0,20 0a10,10 0,1 0,-20 0z" />
        <!-- printed label lines (outer ones stay visible around a thumbnail) -->
        <path android:fillColor="#FFFFE0B2" android:pathData="M38,43.6h12v1.4h-12z" />
        <path android:fillColor="#FFFFE0B2" android:pathData="M40,67h8v1.4h-8z" />
        <path android:fillColor="#FFFFE0B2" android:pathData="M36,49h16v2.2h-16z" />
        <path android:fillColor="#FFFFE0B2" android:pathData="M38,61h9v1.6h-9z" />
        <!-- spindle hole -->
        <path android:fillColor="#FFEEEEEE"
            android:pathData="M42.4,56a1.6,1.6 0,1 0,3.2 0a1.6,1.6 0,1 0,-3.2 0z" />"""


def vector(rotation, comment):
    return f"""<?xml version="1.0" encoding="utf-8"?>
<!-- GENERATED by tools/gen_widget_res.py: {comment} -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="100dp"
    android:height="100dp"
    android:viewportWidth="100"
    android:viewportHeight="100">
    <group android:name="spin" android:pivotX="{CX}" android:pivotY="{CY}" android:rotation="{rotation}">{DISC_PATHS}
    </group>
</vector>
"""


def anim(a, first, second, comment):
    # Base drawable is the still record at the start angle, so the frame drawn before the
    # animator takes over is already at the right angle (no flash at 0 deg).
    return f"""<?xml version="1.0" encoding="utf-8"?>
<!-- GENERATED by tools/gen_widget_res.py: {comment} -->
<animated-vector xmlns:android="http://schemas.android.com/apk/res/android"
    xmlns:aapt="http://schemas.android.com/aapt"
    android:drawable="@drawable/record_rest_{a}">
    <target android:name="spin">
        <aapt:attr name="android:animation">
            <set android:ordering="sequentially">
{first}
{second}
            </set>
        </aapt:attr>
    </target>
</animated-vector>
"""


def obj(frm, to, ms, interp, repeat=False):
    rep = '\n                    android:repeatCount="infinite"\n                    android:repeatMode="restart"' if repeat else ""
    return f"""                <objectAnimator
                    android:propertyName="rotation"
                    android:valueType="floatType"
                    android:valueFrom="{frm}"
                    android:valueTo="{to}"
                    android:duration="{ms}"
                    android:interpolator="@android:interpolator/{interp}"{rep} />"""


def progress_bar(pid, drawable):
    return f"""        <ProgressBar
            android:id="@+id/{pid}"
            android:layout_width="match_parent"
            android:layout_height="match_parent"
            android:importantForAccessibility="no"
            android:indeterminate="true"
            android:indeterminateDrawable="@drawable/{drawable}"
            android:indeterminateOnly="true"
            android:maxWidth="1000dp"
            android:maxHeight="1000dp"
            android:minWidth="0dp"
            android:minHeight="0dp"
            android:visibility="gone" />"""


def layout(name, d):
    # Thumbnail covers the label's inner part: circle of diameter 0.22*d centered at (0.44d, 0.56d).
    td = round(0.22 * d, 1)
    tl = round(0.44 * d - td / 2, 1)
    tt = round(0.56 * d - td / 2, 1)
    bars = "\n".join(progress_bar(f"spin_up_{a}", f"record_up_{a}") for a in ANGLES)
    bars += "\n" + "\n".join(progress_bar(f"spin_down_{a}", f"record_down_{a}") for a in ANGLES)
    return f"""<?xml version="1.0" encoding="utf-8"?>
<!-- GENERATED by tools/gen_widget_res.py. Transparent widget: only the record ({d}dp), its
     title and the next button are drawn. All record layers share one 100x100 viewport. -->
<LinearLayout xmlns:android="http://schemas.android.com/apk/res/android"
    android:id="@android:id/background"
    android:layout_width="match_parent"
    android:layout_height="match_parent"
    android:gravity="center"
    android:orientation="vertical"
    android:padding="4dp">

    <FrameLayout
        android:id="@+id/disc_area"
        android:layout_width="{d}dp"
        android:layout_height="{d}dp"
        android:contentDescription="@string/cd_disc_stopped">

        <!-- Paused: still record at the angle it stopped (RecordWidget sets the drawable). -->
        <ImageView
            android:id="@+id/disc"
            android:layout_width="match_parent"
            android:layout_height="match_parent"
            android:importantForAccessibility="no"
            android:scaleType="fitXY"
            android:src="@drawable/record_rest_0" />

{bars}

        <!-- Video thumbnail in the middle of the label (does not turn: RemoteViews limit). -->
        <ImageView
            android:id="@+id/thumb"
            android:layout_width="{td}dp"
            android:layout_height="{td}dp"
            android:layout_gravity="left|top"
            android:layout_marginLeft="{tl}dp"
            android:layout_marginTop="{tt}dp"
            android:importantForAccessibility="no"
            android:scaleType="centerCrop"
            android:visibility="gone" />

        <ImageView
            android:layout_width="match_parent"
            android:layout_height="match_parent"
            android:importantForAccessibility="no"
            android:scaleType="fitXY"
            android:src="@drawable/record_sheen" />

        <ImageView
            android:id="@+id/tonearm"
            android:layout_width="match_parent"
            android:layout_height="match_parent"
            android:importantForAccessibility="no"
            android:scaleType="fitXY"
            android:src="@drawable/tonearm_up" />
    </FrameLayout>

{title_row(d)}
</LinearLayout>
"""


def button(bid, icon, cd, size):
    return f"""        <ImageButton
            android:id="@+id/{bid}"
            android:layout_width="{size}dp"
            android:layout_height="{size}dp"
            android:layout_marginHorizontal="3dp"
            android:background="@drawable/next_bg"
            android:contentDescription="@string/{cd}"
            android:padding="5dp"
            android:scaleType="fitCenter"
            android:src="@drawable/{icon}" />"""


def title_row(d):
    # Small record: too narrow for a title -> just the two buttons (title kept but hidden
    # so RecordWidget can set it on every size).
    small = d < 100
    size = 26 if small else 28
    title_vis = 'android:visibility="gone"' if small else 'android:layout_marginHorizontal="4dp"'
    return f"""    <!-- No background: text shadow and small dark circles keep it readable on any wallpaper. -->
    <LinearLayout
        android:layout_width="{d}dp"
        android:layout_height="wrap_content"
        android:layout_marginTop="2dp"
        android:gravity="center"
        android:orientation="horizontal">

{button("prev", "ic_prev", "cd_prev", size)}

        <TextView
            android:id="@+id/title"
            android:layout_width="0dp"
            android:layout_height="wrap_content"
            android:layout_weight="1"
            {title_vis}
            android:ellipsize="end"
            android:gravity="center_horizontal"
            android:maxLines="1"
            android:shadowColor="#E6000000"
            android:shadowDx="0"
            android:shadowDy="1"
            android:shadowRadius="4"
            android:singleLine="true"
            android:text="@string/widget_preview_title"
            android:textColor="#FFFFFFFF"
            android:textSize="13sp" />

{button("next", "ic_next", "cd_next", size)}
    </LinearLayout>"""


def ids_kotlin():
    up = ", ".join(f"R.id.spin_up_{a}" for a in ANGLES)
    down = ", ".join(f"R.id.spin_down_{a}" for a in ANGLES)
    rest = ", ".join(f"R.drawable.record_rest_{a}" for a in ANGLES)
    return f"""package com.example.recordwidget

// GENERATED by tools/gen_widget_res.py — index i is angle i * {STEP} degrees.
internal object RecordFrames {{
    const val STEP_DEG = {STEP}
    const val UP_MS = {UP_MS}L
    const val UP_DEG = {UP_DEG}
    const val DOWN_MS = {DOWN_MS}L
    const val DOWN_DEG = {DOWN_DEG}
    const val TURN_MS = {TURN_MS}L
    val UP_IDS = intArrayOf({up})
    val DOWN_IDS = intArrayOf({down})
    val REST_DRAWABLES = intArrayOf({rest})
}}
"""


def write(path, text):
    with open(path, "w", encoding="utf-8") as f:
        f.write(text)


def main():
    d = os.path.join(RES, "drawable")
    write(os.path.join(d, "record_disc.xml"), vector(0, "the record (group 'spin' is animated)"))
    for a in ANGLES:
        write(os.path.join(d, f"record_rest_{a}.xml"), vector(a, f"still record at {a} deg"))
        write(os.path.join(d, f"record_up_{a}.xml"), anim(
            a,
            obj(a, a + UP_DEG, UP_MS, "accelerate_quad"),
            obj(a + UP_DEG, a + UP_DEG + 360, TURN_MS, "linear", repeat=True),
            f"spin-up from {a} deg, then 33 1/3 rpm"))
        end = a + DOWN_DEG
        write(os.path.join(d, f"record_down_{a}.xml"), anim(
            a,
            obj(a, end, DOWN_MS, "decelerate_quad"),
            obj(end, end, 3600000, "linear", repeat=True),
            f"spin-down from {a} deg to {end % 360} deg, then hold"))
    sizes = [("widget_record", 72), ("widget_record_m", 130), ("widget_record_l", 190)]
    for name, size in sizes:
        write(os.path.join(RES, "layout", f"{name}.xml"), layout(name, size))
    write("app/src/main/java/com/example/recordwidget/RecordFrames.kt", ids_kotlin())


if __name__ == "__main__":
    main()
